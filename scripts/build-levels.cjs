// Compile the editable JSON registry to an offline file:// compatible script.
const fs=require('node:fs');
const path=require('node:path');
require('../static/game/js/core.js');
const source=path.resolve(__dirname,'../static/game/data/levels.json');
const levels=JSON.parse(fs.readFileSync(source,'utf8'));
const ids=new Set();
for(const level of levels){GameCore.validateLevel(level);if(ids.has(level.id))throw Error('Duplicate level id: '+level.id);ids.add(level.id);}
fs.writeFileSync(path.resolve(__dirname,'../static/game/js/levels.js'),'// Generated by scripts/build-levels.cjs. Edit data/levels.json instead.\n(function(root){root.LEVELS='+JSON.stringify(levels)+';})(typeof window!==\'undefined\'?window:globalThis);\n');
console.log('Validated and compiled '+levels.length+' offline levels.');
